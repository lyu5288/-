export interface HangulLetter {
  id: string;
  char: string;
  name: string;
  phonics: string;
  type: 'consonant' | 'double_consonant' | 'vowel';
  sampleWord: string;
  sampleEmoji: string;
  soundDescription: string;
  color: string;
  bgColor: string;
  borderColor: string;
  // Tracing stroke guide instructions
  strokeCount: number;
  strokeHints: string[];
}

export interface WordPuzzleItem {
  id: string;
  word: string;
  syllables: string[];
  emoji: string;
  category: '동물' | '과일·음식' | '탈것·물건' | '자연';
  hint: string;
  color: string;
}

export interface MatchingCard {
  id: string;
  pairId: string;
  type: 'letter' | 'image' | 'word';
  content: string; // letter/word or emoji
  label: string;
  bgColor: string;
}

export interface StickerItem {
  id: string;
  title: string;
  description: string;
  icon: string;
  unlocked: boolean;
  unlockedAt?: string;
}

